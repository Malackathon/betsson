"""Domain models and data contracts for the Betsson Game Validation project.

Defines Pydantic v2 schemas and enums used across all testing agents:
- CheckStatus: enum for soft-check and overall report statuses
- CheckResult: structured outcome of a single validation check
- AgentId: identifiers for the four parallel sub-agents
- Market: target market identifiers (COM, PE)
- SubAgentReport: execution report for an individual sub-agent
- MasterReport: aggregated report across all sub-agents
- GeminiReading and subclasses: structured contracts for Gemini vision responses
- MarketConfig: market-specific configuration and selectors
"""

from __future__ import annotations

from datetime import datetime
from enum import Enum, StrEnum
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field


class CheckStatus(StrEnum):
    """Execution status for a single check or aggregated report."""

    PASS = "PASS"
    FAIL = "FAIL"
    INFO = "INFO"
    ERROR = "ERROR"
    SKIP = "SKIP"

    @classmethod
    def _missing_(cls, value: object) -> "CheckStatus | None":
        """Support case-insensitive lookup."""
        if isinstance(value, str):
            val_upper = value.upper()
            for member in cls:
                if member.value == val_upper:
                    return member
        return None


class CheckResult(BaseModel):
    """Represents the outcome of a single validation check (soft check).

    Attributes:
        id: Unique identifier for the check (e.g. 'S1.01').
        name: Descriptive human-readable name of the check.
        expected: Expected value or condition description.
        observed: Actual value or condition observed during execution.
        detail: Supplementary details, reasoning, or exception messages.
        status: Execution status (PASS, FAIL, INFO, ERROR, SKIP).
    """

    model_config = ConfigDict(use_enum_values=False)

    id: str
    name: str
    expected: str | None = None
    observed: str | None = None
    detail: str | None = None
    status: CheckStatus


