class SubAgentReport(BaseModel):
    """Execution report generated by a single sub-agent run.

    Attributes:
        agent_id: Identifier of the running agent.
        market: Market being validated (COM or PE).
        scenario: Scenario number (1 for real spin, 2 for insufficient funds).
        checks: Ordered list of CheckResult records recorded during execution.
        evidence_dir: Local path to the directory storing artifacts and screenshots.
        video_path: Local path to the recorded execution video, if captured.
        started_at: UTC timestamp when the agent execution started.
        finished_at: UTC timestamp when the agent execution finished.
    """

    model_config = ConfigDict(use_enum_values=False)

    agent_id: AgentId
    market: Market
    scenario: Literal[1, 2]
    checks: list[CheckResult]
    evidence_dir: Path
    video_path: Path | None = None
    started_at: datetime
    finished_at: datetime

    @property
    def overall(self) -> CheckStatus:
        """Derive the overall execution status from individual checks.

        Returns:
            CheckStatus.ERROR if any check resulted in ERROR.
            CheckStatus.PASS if all checks are PASS, INFO, or SKIP.
            CheckStatus.FAIL otherwise (including when any check is FAIL).
        """
        if any(c.status == CheckStatus.ERROR for c in self.checks):
            return CheckStatus.ERROR
        if all(
            c.status in (CheckStatus.PASS, CheckStatus.INFO, CheckStatus.SKIP)
            for c in self.checks
        ):
            return CheckStatus.PASS
        return CheckStatus.FAIL


class MasterReport(BaseModel):
    """Aggregated report consolidating all sub-agent execution runs.

    Attributes:
        reports: List of SubAgentReport instances from executed sub-agents.
    """

    model_config = ConfigDict(use_enum_values=False)

    reports: list[SubAgentReport]

    @property
    def total_pass(self) -> int:
        """Count of all checks with PASS status across all sub-agent reports."""
        return sum(
            1
            for report in self.reports
            for check in report.checks
            if check.status == CheckStatus.PASS
        )

    @property
    def total_fail(self) -> int:
        """Count of all checks with FAIL status across all sub-agent reports."""
        return sum(
            1
            for report in self.reports
            for check in report.checks
            if check.status == CheckStatus.FAIL
        )

    @property
    def all_passed(self) -> bool:
        """True if every SubAgentReport.overall is PASS.

        Returns False if there are no reports.
        """
        if not self.reports:
            return False
        return all(report.overall == CheckStatus.PASS for report in self.reports)


class GeminiReading(BaseModel):
    """Base contract for structured outputs extracted by Gemini vision."""

    model_config = ConfigDict(use_enum_values=False)


class GeminiBalanceReading(GeminiReading):
    """Structured balance reading extracted from the lobby or game interface.

    Attributes:
        raw_text: Raw unparsed text identified in the image region.
        amount: Extracted monetary amount string (e.g. '1234.56' or '1.234,56').
        currency_symbol: Extracted currency symbol or code (e.g. '€', 'S/', 'EUR', 'PEN').
        legible: Indicates whether the balance text was legible and unambiguous.
    """

    raw_text: str
    amount: str | None = None
    currency_symbol: str | None = None
    legible: bool = True


class GeminiHudReading(GeminiReading):
    """Structured reading of in-game HUD fields (credit, bet, win).

    Attributes:
        raw_text: Raw unparsed text identified across the HUD area.
        credit: Extracted in-game credit balance string.
        bet: Extracted current bet amount string.
        win: Extracted win amount string from the last spin.
        currency_symbol: Extracted currency symbol or code.
        legible: Indicates whether all expected HUD fields were legible.
    """

    raw_text: str
    credit: str | None = None
    bet: str | None = None
    win: str | None = None
    currency_symbol: str | None = None
    legible: bool = True


class GeminiMessageReading(GeminiReading):
    """Structured reading of modal dialogs, error alerts, or banner messages.

    Attributes:
        raw_text: Raw unparsed text detected inside the dialog or modal.
        message_text: Cleaned and normalized text of the displayed message.
        detected_language: Detected language code (e.g. 'en', 'es').
        legible: Indicates whether the message text was clearly readable.
    """

    raw_text: str
    message_text: str | None = None
    detected_language: str | None = None
    legible: bool = True


class GeminiSpinLocation(GeminiReading):
    """Detected location coordinates of the game's spin button.

    Attributes:
        raw_text: Raw descriptive text or coordinates explanation from vision model.
        x: Normalized X coordinate (0.0 to 1.0) of the spin button center.
        y: Normalized Y coordinate (0.0 to 1.0) of the spin button center.
        legible: Indicates whether the spin button was clearly identified.
    """

    raw_text: str
    x: float | None = None
    y: float | None = None
    legible: bool = True


class MarketConfig(BaseModel):
    """Market-specific configuration and selectors loaded from markets.json.

    Attributes:
        url: Entry URL for the market's Betsson website.
        locale: Language locale (e.g. 'en', 'es').
        currency: ISO currency code (e.g. 'EUR', 'PEN').
        currency_symbol: Currency symbol (e.g. '€', 'S/').
        keywords_insufficient: Keywords signaling insufficient balance in notifications.
        game_candidates: Preferred Pragmatic Play game titles ordered by suitability.
        selectors: CSS or XPath selectors for page interactions.
        notes: Operational notes, observations, or known risks for this market.
    """

    model_config = ConfigDict(use_enum_values=False)

    url: str
    locale: str
    currency: str
    currency_symbol: str
    keywords_insufficient: list[str]
    game_candidates: list[str]
    selectors: dict[str, str] = Field(default_factory=dict)
    notes: str = ""


